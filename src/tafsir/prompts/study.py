"""MCP Prompts: study templates for Quranic scholarship."""

from __future__ import annotations

from typing import Annotated

from mcp.server.fastmcp import FastMCP
from pydantic import Field


def study_ayah(
    surah: Annotated[int, Field(ge=1, le=114, description="رقم السورة")],
    ayah: Annotated[int, Field(ge=1, description="رقم الآية")],
) -> str:
    """قالب دراسة آية: نص + إعراب + تفسير + معاني الكلمات."""
    return f"""\
# دراسة الآية {surah}:{ayah}

استخدم الأدوات التالية بالترتيب لدراسة هذه الآية دراسةً وافية:

## 1. جلب نص الآية
استدعِ: `fetch_ayah(surah={surah}, ayah={ayah})`
→ اعرض النص العربي كاملاً مع رقم السورة والآية.

## 2. التفسير
استدعِ: `fetch_tafsir(surah={surah}, ayah={ayah}, source="saadi")`
→ اعرض تفسير السعدي (الأوجز والأيسر للمبتدئ).
ثم: `fetch_tafsir(surah={surah}, ayah={ayah}, source="katheer")`
→ اعرض تفسير ابن كثير لمن أراد التوسع.

## 3. سبب النزول (إن وُجد)
استدعِ: `fetch_nuzool_reason(surah={surah}, ayah={ayah})`
→ إن أُعيد بيانات: اعرضها. إن لم تُوجد: نبّه بذلك.

## 4. تحليل الكلمات
استدعِ: `analyze_word(surah={surah}, ayah={ayah}, word_no=1)`
→ كرر لكل كلمة (زِد word_no واحداً في كل مرة حتى تنتهي الآية).
→ أبرز: المعنى، الإعراب، الجذر، الصيغة الصرفية.

## 5. أحكام التجويد
استدعِ: `fetch_ayah(surah={surah}, ayah={ayah}, include=["tajweed"])`
→ اعرض نص التجويد الملوّن مع شرح الأحكام الظاهرة.

## 6. القراءات
استدعِ: `get_qeraat_variants(surah={surah}, ayah={ayah})`
→ إن وُجدت قراءات: اعرضها مع أصحابها. إن لم تُوجد: نبّه بذلك.

---
**تعليمات العرض:**
- لا تُلخّص النصوص القرآنية أو التفسيرية — اعرضها كاملةً كما أُعيدت من قاعدة البيانات.
- اذكر المصدر (المؤلف + الكتاب) مع كل تفسير.
- استخدم العناوين والفقرات لتنظيم النتائج.
"""


def compare_tafsirs(
    surah: Annotated[int, Field(ge=1, le=114, description="رقم السورة")],
    ayah: Annotated[int, Field(ge=1, description="رقم الآية")],
) -> str:
    """قالب مقارنة التفاسير الخمسة لآية واحدة."""
    return f"""\
# مقارنة التفاسير — الآية {surah}:{ayah}

## الخطوة 1: جلب نص الآية
استدعِ: `fetch_ayah(surah={surah}, ayah={ayah})`
→ اعرض النص في الأعلى مرجعاً ثابتاً طوال الصفحة.

## الخطوة 2: جمع التفاسير الخمسة
نفّذ الاستدعاءات التالية (يمكن بالتوازي):

| المصدر | الاستدعاء |
|--------|-----------|
| الطبري (ت. 310هـ) | `fetch_tafsir(surah={surah}, ayah={ayah}, source="tabary")` |
| ابن كثير (ت. 774هـ) | `fetch_tafsir(surah={surah}, ayah={ayah}, source="katheer")` |
| البغوي (ت. 510هـ) | `fetch_tafsir(surah={surah}, ayah={ayah}, source="baghawy")` |
| السعدي (ت. 1376هـ) | `fetch_tafsir(surah={surah}, ayah={ayah}, source="saadi")` |
| الميسر | `fetch_tafsir(surah={surah}, ayah={ayah}, source="moyassar")` |

## الخطوة 3: العرض
اعرض كل تفسير في قسم منفصل بعنوان يتضمن اسم المؤلف والكتاب وسنة الوفاة.
اعرض النص كاملاً — لا تختصره.

## الخطوة 4: ملاحظات المقارنة
بعد عرض التفاسير، أضف قسم "ملاحظات" يُبيّن:
- النقاط التي أجمع عليها المفسرون.
- النقاط التي تباينوا فيها (إن وُجدت).
- أيّ تفسير أطول/أكثر تفصيلاً وأيّها أوجز.

---
**تعليمات صارمة:** لا تُعدّل أي نص تفسيري. اعرضه حرفياً كما جاء من قاعدة البيانات.
"""


def root_study(
    root: Annotated[str, Field(min_length=2, max_length=6, description="الجذر العربي (مثال: رحم، كتب، علم)")],
) -> str:
    """قالب دراسة جذر قرآني: إحصاء + أوزان + سياقات."""
    return f"""\
# دراسة الجذر: {root}

## الخطوة 1: الإحصاء العام
استدعِ: `get_root_stats(root="{root}")`
→ اعرض: عدد المرات، عدد السور، عدد الآيات، عدد الأوزان المختلفة.
→ إن لم يُوجد الجذر: أنهِ الدراسة مع تنبيه واضح.

## الخطوة 2: استعراض المواضع
استدعِ: `find_root_occurrences(root="{root}", limit=100)`
→ اعرض النتائج في جدول: السورة | الآية | رقم الكلمة | الكلمة | عدد التكرار.
→ إن تجاوزت النتائج 30 موضعاً، اعرض أول 30 وأشر إلى العدد الكلي.

## الخطوة 3: أوزان الكلمات
من قائمة مواضع الورود، استخرج الكلمات الفريدة وصنّفها حسب الوزن الصرفي.

## الخطوة 4: سياقات مختارة
اختر 5 مواضع تمثيلية (من سور مختلفة إن أمكن).
لكل موضع: استدعِ `fetch_ayah(surah=X, ayah=Y)` واعرض الآية كاملة.

## الخطوة 5: خلاصة دلالية
استناداً إلى المعطيات أعلاه، اكتب فقرة موجزة عن:
- الحقل الدلالي الرئيسي للجذر في القرآن الكريم.
- السور التي تركّزت فيها الكلمة أكثر من غيرها.

---
**تنبيه:** البحث يشمل النص الكامل للقرآن (6236 آية). قد تستغرق الاستدعاءات ثوانٍ.
"""


def surah_overview(
    surah: Annotated[int, Field(ge=1, le=114, description="رقم السورة (1-114)")],
) -> str:
    """قالب نظرة شاملة على سورة: أهداف، فضائل، إحصاءات، مقدمة."""
    return f"""\
# نظرة شاملة على سورة رقم {surah}

## الخطوة 1: المعلومات الأساسية
استدعِ: `fetch_surah_info(surah={surah})`
→ اعرض: اسم السورة، نوع التنزيل (مكية/مدنية)، ترتيب النزول،
         عدد الآيات، نوع البداية (حروف مقطّعة؟).

## الخطوة 2: الإحصاءات التفصيلية
استدعِ: `get_surah_statistics(surah={surah})`
→ اعرض في جدول: عدد الكلمات، الحروف، الحركات، أطول كلمة،
                  أكثر حرف تكراراً، الكلمة الأكثر ورودًا.
→ اعرض: أهداف السورة، فضائلها، معلومات أسماءها.

## الخطوة 3: فوائد صفحات السورة
احسب رقم الصفحة الأولى تقريبياً (كل صفحة ~15 آية).
استدعِ `get_page_fawaed(page=X)` لعدة صفحات تغطي السورة.
→ اعرض الفوائد المستخرجة.

## الخطوة 4: أسباب نزول آيات مختارة
استدعِ: `search_quran_text(query="...", surah_filter=[{surah}])` للبحث عن موضوع يميز السورة.
ثم استدعِ `fetch_nuzool_reason` لآيات ذات أسباب نزول معروفة في هذه السورة.

## الخطوة 5: العرض النهائي
رتّب المعلومات في أقسام:
1. تعريف السورة
2. محاورها ومقاصدها
3. إحصاءاتها
4. فضائلها
5. فوائد مختارة

---
**تذكير:** اعرض نصوص الفضائل والأهداف كاملةً دون اختصار.
"""


def tajweed_lesson(
    surah: Annotated[int, Field(ge=1, le=114, description="رقم السورة")],
    ayah: Annotated[int, Field(ge=1, description="رقم الآية")],
) -> str:
    """قالب درس تجويد: أحكام الآية + القراءات + التحليل الكلمي."""
    return f"""\
# درس التجويد — الآية {surah}:{ayah}

## الخطوة 1: نص الآية العادي والمُجوَّد
استدعِ: `fetch_ayah(surah={surah}, ayah={ayah})`
→ اعرض النص العادي أولاً.
استدعِ نفس الأداة مع `include=["tajweed"]`.
→ اعرض نص التجويد.

## الخطوة 2: تحليل الكلمات التجويدية
لكل كلمة في الآية، استدعِ:
`analyze_word(surah={surah}, ayah={ayah}, word_no=N)`
→ ابحث في حقل `irab` عن الحركة (ضمة/فتحة/كسرة/سكون).
→ لاحظ: التنوين، الشدة، المدود الظاهرة في إعراب الكلمة.

## الخطوة 3: القراءات
استدعِ: `get_qeraat_variants(surah={surah}, ayah={ayah})`
→ اعرض القراءات مع أسماء القراء.
→ وضّح الفرق الصوتي أو النحوي بين القراءات.

## الخطوة 4: الأحكام التجويدية المستنبطة
استناداً للبيانات أعلاه، اذكر:
- أحكام النون الساكنة والتنوين (إدغام، إخفاء، إظهار، إقلاب).
- أحكام الميم الساكنة.
- المدود (مد طبيعي، عارض، لازم...).
- أحكام الراء واللام.
- أي حكم آخر ظاهر في الآية.

## الخطوة 5: خلاصة للطالب
اكتب ملخصاً للطالب يذكر أبرز 3-5 أحكام تجويدية في هذه الآية مع مثال من النص.

---
**تنبيه:** نصوص التجويد في قاعدة البيانات مشكّلة ومرمّزة — اعرضها كما هي.
"""


def register(mcp: FastMCP) -> None:
    mcp.prompt(name="study_ayah")(study_ayah)
    mcp.prompt(name="compare_tafsirs")(compare_tafsirs)
    mcp.prompt(name="root_study")(root_study)
    mcp.prompt(name="surah_overview")(surah_overview)
    mcp.prompt(name="tajweed_lesson")(tajweed_lesson)
